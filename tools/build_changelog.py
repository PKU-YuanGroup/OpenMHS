#!/usr/bin/env python3
"""Keep the per-fragment part of CHANGELOG.md in step with MHS/changes/*.md.  Standard library only.

    python3 tools/build_changelog.py            # rewrite the generated block of CHANGELOG.md
    python3 tools/build_changelog.py --check    # exit 1 when the block is missing or out of date

CHANGELOG.md has a hand-written summary at the top and, between two marker comments, one section per change fragment:
the fragment's title, its first paragraph and a link. The fragments (``MHS/changes/*.md``) are the detailed records, written
by whoever made the change; this block only indexes them, so a fragment that is added later cannot be forgotten.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEFAULT_ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- BEGIN FRAGMENTS (generated by tools/build_changelog.py; edit the fragment, not this block) -->"
END = "<!-- END FRAGMENTS -->"
LIMIT = 480


def fragment_key(path: Path):
    name = path.stem
    match = re.match(r"WP-(\d+)", name)
    if match:
        return (0, int(match.group(1)), name)
    for rank, prefix in enumerate(("MERGE", "RESIDUAL", "CLEANUP", "FINAL-REVIEW"), 1):
        if name.startswith(prefix):
            return (rank, 0, name)
    return (9, 0, name)


def summary(text: str) -> tuple[str, str]:
    """(title, first plain paragraph) of a fragment."""
    lines = text.splitlines()
    title = next((line[2:].strip() for line in lines if line.startswith("# ")), "")
    start = next((i for i, line in enumerate(lines) if line.startswith("# ")), -1) + 1
    paragraph: list[str] = []
    in_fence = False
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        plain = stripped and not stripped.startswith(("|", "-", "*", "#", ">", "<!--"))
        if plain:
            paragraph.append(stripped)
        elif paragraph:
            break
    body = " ".join(paragraph)
    if len(body) > LIMIT:
        body = body[:LIMIT].rsplit(" ", 1)[0].rstrip(",;:") + " ..."
    return title, body


def block(root: Path) -> str:
    out = [BEGIN, ""]
    for path in sorted((root / "MHS" / "changes").glob("*.md"), key=fragment_key):
        title, body = summary(path.read_text(encoding="utf-8"))
        out += [f"### {title or path.stem}", "", f"[`MHS/changes/{path.name}`](MHS/changes/{path.name})" + (f": {body}" if body else ""), ""]
    out.append(END)
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 when CHANGELOG.md is out of date")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="repository root (default: found from this file)")
    args = parser.parse_args(argv)

    changelog = args.root / "CHANGELOG.md"
    text = changelog.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("error: CHANGELOG.md has no generated fragments block (markers missing)", file=sys.stderr)
        return 1
    new = text.split(BEGIN, 1)[0] + block(args.root) + text.split(END, 1)[1]
    if args.check:
        if new != text:
            print("CHANGELOG.md is out of date: run python3 tools/build_changelog.py", file=sys.stderr)
            return 1
        print("CHANGELOG.md lists every change fragment")
        return 0
    changelog.write_text(new, encoding="utf-8")
    print(f"wrote {changelog.relative_to(args.root)}: {new.count('### ') - text.count('### ') + text.count('### ')} fragment section(s) in the block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
