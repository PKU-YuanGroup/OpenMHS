"""Hardware backend of the PAMILA read-only middle-layer variable list.

The gate never imports this module.  ``connect`` runs only when an operator loads the hardware backend
(``mhs.adapter.load_driver(..., backend="hardware", allow_hardware=True, ...)``); it then imports ``pamila`` and
loads a facility configuration generated by the PAMILA examples.

Deployment requirements, all outside the upstream Facts:

* a generated facility configuration directory containing ``<machine_name>/sim_configs.yaml`` and the selected
  configuration folder (``examples/nb_gen/03_mlvl.py:23`` shows the layout; the clone ships no generated folder);
* the ``pamila`` package with its dependencies (``ophyd``, ``pydantic``, ``pint``, and ``pyepics`` for live PVs);
* the ``PAMILA_FACILITY`` environment variable.  This factory sets it before the import and refuses a value that
  disagrees with an already-set variable, because ``src/pamila/machine.py:8-13`` reads it at import time.

The factory returns the selected ``MiddleLayerVariableListRO``.  An existing list is selected by name; otherwise
one is built from the given read-only middle-layer variables and its connection is waited for once, with the
operator-given ``timeout_s``.  The list never writes a machine setpoint (``src/pamila/middle_layer/var_list.py:582-592``).

Nothing in this package has run on hardware.  The package is model-authored and unreviewed (``reviewed_by`` is
null); at R0 (the package's risk since the model review) the loader does not require a human review before loading,
so run this backend only with a person at the machine and with the facility's own stop procedure at hand.
"""

from pathlib import Path


def connect(*, config_dir, name, mlv_names=None, facility="nsls2", machine_name="SR",
            machine_mode="LIVE", timeout_s=5.0):
    if not isinstance(name, str) or not name.strip():
        raise ValueError("name must be the non-empty name of the middle-layer variable list")
    if not isinstance(machine_name, str) or not machine_name.strip():
        raise ValueError("machine_name must be the non-empty name of the machine in the facility configuration")
    if not isinstance(facility, str) or not facility.strip():
        raise ValueError("facility must be the non-empty PAMILA facility name")
    if machine_mode not in ("LIVE", "SIMULATOR"):
        raise ValueError("machine_mode must be 'LIVE' or 'SIMULATOR'")
    if isinstance(timeout_s, bool) or not isinstance(timeout_s, (int, float)) or not timeout_s > 0:
        raise ValueError("timeout_s must be a positive number of seconds")
    directory = Path(config_dir)
    if not directory.is_dir():
        raise ValueError("config_dir must be an existing PAMILA facility configuration directory")
    if mlv_names is not None:
        if isinstance(mlv_names, str) or not isinstance(mlv_names, (list, tuple)) or not mlv_names:
            raise ValueError("mlv_names must be a non-empty list of middle-layer variable names")
        if not all(isinstance(item, str) and item.strip() for item in mlv_names):
            raise ValueError("every mlv_names entry must be a non-empty middle-layer variable name")

    import os

    if "PAMILA_FACILITY" in os.environ and os.environ["PAMILA_FACILITY"] != facility:
        raise RuntimeError(
            "PAMILA_FACILITY is already set to a different facility; start a fresh interpreter for this deployment")
    os.environ["PAMILA_FACILITY"] = facility

    import pamila
    from pamila import MachineMode, Q_, load_machine, set_machine_mode
    from pamila.middle_layer import (
        MiddleLayerVariableListRO,
        MiddleLayerVariableListROSpec,
        MiddleLayerVariableRO,
    )

    if pamila.machine.get_facility_name() != facility:
        raise RuntimeError("pamila was already imported for a different facility; start a fresh interpreter")

    set_machine_mode(MachineMode[machine_mode])
    machine = load_machine(machine_name, dirpath=directory)

    existing = machine.get_all_mlvls()
    if name in existing:
        mlvl = existing[name]
        if not isinstance(mlvl, MiddleLayerVariableListRO):
            raise TypeError(f"the existing list {name!r} is not a MiddleLayerVariableListRO")
        mlvl.wait_for_connection(all_modes=False, timeout=Q_(f"{timeout_s} s"))
        return mlvl

    if mlv_names is None:
        raise ValueError(
            f"no list named {name!r} is defined in the machine configuration; pass mlv_names to build one")
    variables = machine.get_all_mlvs()
    missing = [item for item in mlv_names if item not in variables]
    if missing:
        raise ValueError(f"middle-layer variables not found in the machine configuration: {', '.join(missing)}")
    members = [variables[item] for item in mlv_names]
    writable = [mlv.name for mlv in members if not isinstance(mlv, MiddleLayerVariableRO)]
    if writable:
        raise TypeError(
            "a read-only list needs read-only middle-layer variables; these are writable: " + ", ".join(writable))

    spec = MiddleLayerVariableListROSpec(name=name, exist_ok=True, mlvs=members)
    mlvl = MiddleLayerVariableListRO(spec)
    mlvl.wait_for_connection(all_modes=False, timeout=Q_(f"{timeout_s} s"))
    return mlvl
