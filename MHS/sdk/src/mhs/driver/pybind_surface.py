"""Source-only evidence for a native class that the upstream exposes through pybind11 binding code (gate G7).

Some upstream Python clients exist only as C++ classes bound with pybind11: the clone has no Python class whose AST
G7 could read, only the binding source (often generated by the binder tool). A driver names such a class with

    native = "pybind:<path/of/the/binding.cpp>#<scope>.<Name>"

for example ``pybind:modules/comms/python/generated-sources-pybind/mvsim/Comms/Client.cpp#mvsim.Client``. The selector
is evidence metadata, never imported or built; ``backends`` constructs the runtime object.

The file is read as a regular blob at the pinned commit (the same rule as ``pyfile:`` selectors). The class must be
declared there exactly once as ``pybind11::class_<...> <var>(M("<scope>"), "<Name>", ...)`` (binder's module getter,
``<scope>`` the C++ namespace with ``::`` for each ``.``), or as ``py::class_<...> <var>(<module>, "<Name>", ...)`` for
a selector without a scope; a declaration without a variable (members bound by chained ``.def`` calls) is reported,
not read. Its members are the string names of ``<var>.def(...)``, ``def_static``,
``def_readwrite``, ``def_readonly``, ``def_property`` and ``def_property_readonly`` calls made at the declaration's
own brace depth, until that block ends; a nested block (binder's nested classes reuse the variable name) contributes
nothing. Comments are skipped; macros, templates and preprocessor branches are not evaluated, and argument shapes,
return types, the binding's GIL handling and the behaviour of the bound C++ code are not checked.
"""

from __future__ import annotations

import re
from typing import Any

from .source_selector import PybindSelector, parse_pybind_selector
from .upstream import Surface

__all__ = ["PybindSelector", "parse_pybind_selector", "pybind_surface"]

_MEMBER_CALLS = ("def", "def_static", "def_readwrite", "def_readonly", "def_property", "def_property_readonly")


def _code(text: str) -> tuple[str, list[int]]:
    """``text`` with comments blanked (string literals kept), and the brace depth before each character."""
    out = []
    depths = []
    depth = 0
    index = 0
    length = len(text)
    while index < length:
        char = text[index]
        pair = text[index:index + 2]
        if pair == "//":
            end = text.find("\n", index)
            end = length if end < 0 else end
            out.append(" " * (end - index))
            depths.extend([depth] * (end - index))
            index = end
            continue
        if pair == "/*":
            end = text.find("*/", index + 2)
            end = length if end < 0 else end + 2
            chunk = text[index:end]
            out.append("".join("\n" if item == "\n" else " " for item in chunk))
            depths.extend([depth] * len(chunk))
            index = end
            continue
        if char in "\"'":
            end = index + 1
            while end < length and text[end] != char:
                end += 2 if text[end] == "\\" else 1
            end = min(end + 1, length)
            out.append(text[index:end])
            depths.extend([depth] * (end - index))
            index = end
            continue
        depths.append(depth)
        out.append(char)
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        index += 1
    return "".join(out), depths


def _template_end(code: str, start: int) -> int:
    """Index just after the ``>`` that closes the template argument list opened at ``start`` (``-1`` if none)."""
    level = 0
    for index in range(start, min(len(code), start + 2000)):
        char = code[index]
        if char == "<":
            level += 1
        elif char == ">":
            level -= 1
            if level == 0:
                return index + 1
        elif char in ";{}":
            return -1
    return -1


def pybind_surface(tree: Any, selector: PybindSelector) -> Surface:
    """The member names of the selected pybind11 class, read from its binding source at the pinned commit."""
    from .source_surface import regular_source

    surface = Surface(selector.value)
    try:
        text = regular_source(tree, selector.path)
    except ValueError as exc:
        surface.problems.append(str(exc))
        return surface
    code, depths = _code(text)
    if selector.scope:
        scope = r'M\(\s*"' + re.escape(selector.scope) + r'"\s*\)'
    else:
        scope = r"[A-Za-z_][A-Za-z0-9_]*"
    declaration = re.compile(r"\s*([A-Za-z_][A-Za-z0-9_]*)?\s*\(\s*" + scope + r'\s*,\s*"' + re.escape(selector.name)
                             + r'"\s*[,)]')
    found: list[tuple[int, str]] = []
    for match in re.finditer(r"(?:\bpybind11|\bpy)::class_\s*<", code):
        end = _template_end(code, match.end() - 1)
        if end < 0:
            continue
        declared = declaration.match(code, end)
        if declared is not None:
            found.append((match.start(), declared.group(1)))
    if len(found) != 1:
        what = "no" if not found else f"{len(found)}"
        surface.problems.append(f"{selector.path} has {what} pybind11 class_ declaration of "
                                f"{(selector.scope + '::') if selector.scope else ''}{selector.name} at the pinned commit")
        return surface
    position, variable = found[0]
    if variable is None:
        surface.problems.append(f"{selector.path} declares {selector.name} without a variable name; members bound by "
                                "chained calls are not read")
        return surface
    depth = depths[position]
    surface.file = selector.path
    surface.line = text.count("\n", 0, position) + 1
    calls = re.compile(r"\b" + re.escape(variable) + r"\s*\.\s*(" + "|".join(_MEMBER_CALLS) + r')\s*\(\s*"'
                       r"([A-Za-z_][A-Za-z0-9_]*)\"")
    # The declaration's block ends at the first character whose depth is below the declaration's own.
    block_end = next((index for index in range(position, len(depths)) if depths[index] < depth), len(code))
    for match in calls.finditer(code, position, block_end):
        if depths[match.start()] == depth:  # a nested block (a nested class reusing the name) adds nothing
            surface.names.add(match.group(2))
    surface.classes = [f"{selector.path}:{selector.name}"]
    if not surface.names:
        surface.problems.append(f"{selector.path}: the pybind11 class {selector.name} binds no named member")
    return surface
