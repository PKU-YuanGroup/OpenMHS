#!/usr/bin/env python3
"""Read-only view of the per-repo driver packages: ``MHS/drivers/<track>/<owner>__<repo>/``.

Per-repo progress lives only in the driver packages and in
``MHS/registry/overrides/**`` (plan 3.11); regenerating the registry reads
them and never writes there.  This module reads, per driver directory:

``driver.lock.json``  pinned upstream commit, licence, authors and reviewers
                      (``MHS/schema/driver-lock.schema.json``)
``RESULT.json``       the author's outcome: pass with a gate digest, or blocked /
                      skip-proposed with blocked codes
                      (``MHS/schema/driver-result.schema.json``)
``check-report.json`` the gate's own report (``MHS/schema/check-report.schema.json``);
                      generated by every gate run and not committed, so a record names it
                      only as the evidence of an operator-run hardware check
``task.json``         the card the package was written from
``reference.json``    the generated reference file (``MHS/schema/reference.schema.json``)

and derives the registry overlay: the evidence state (``contract_checked`` for a
pass on a fake or simulated backend; ``hardware_checked`` only for an
operator-run hardware check with a reviewed lock), the adapter state, and the
blocked codes a blocked result adds to the card.  CI re-runs the gate and never
trusts RESULT.json; the overlay is an index, not a proof.

Stdlib only.  Nothing here imports or executes driver code.
"""

from __future__ import annotations

import glob
import hashlib
import json
import os
import re
from dataclasses import dataclass, field
from typing import Any

HERE = os.path.dirname(os.path.abspath(__file__))
WORKSPACE = os.path.abspath(os.path.join(HERE, "..", ".."))
DRIVERS_DIR = os.path.join(WORKSPACE, "MHS", "drivers")
OVERRIDES_DIR = os.path.join(HERE, "overrides")
TRACKS = ("labs", "robots")
_DIR_NAME = re.compile(r"^[A-Za-z0-9_.-]+__[A-Za-z0-9_.-]+$")
FILES = ("driver.lock.json", "RESULT.json", "check-report.json", "task.json", "reference.json")
#: Files the gate rewrites on every run (new timestamps) and nobody commits: a record names one only as the evidence
#: of an operator-run hardware check, so regenerating the registry gives the same bytes whether a report is present.
GENERATED = frozenset({"check-report.json"})


@dataclass
class Overlay:
    """What one driver package says about its repo (all values read from disk)."""

    key: str                      # "<track>/<owner>__<repo>"
    path: str                     # repository-relative driver directory
    docs: dict[str, Any] = field(default_factory=dict)      # file name -> parsed JSON
    errors: list[str] = field(default_factory=list)          # unreadable or malformed files

    @property
    def lock(self) -> dict[str, Any] | None:
        return self.docs.get("driver.lock.json")

    @property
    def result(self) -> dict[str, Any] | None:
        return self.docs.get("RESULT.json")

    @property
    def report(self) -> dict[str, Any] | None:
        return self.docs.get("check-report.json")

    @property
    def task(self) -> dict[str, Any] | None:
        return self.docs.get("task.json")

    @property
    def reference(self) -> dict[str, Any] | None:
        return self.docs.get("reference.json")

    @property
    def status(self) -> str | None:
        result = self.result or {}
        return result.get("status") if isinstance(result, dict) else None

    def passed(self) -> bool:
        result = self.result or {}
        gate = result.get("gate") if isinstance(result, dict) else None
        return self.status == "pass" and isinstance(gate, dict) and bool(gate.get("digest")) and not gate.get("failed")

    def hardware_checked(self) -> bool:
        """An operator-run hardware check: a passing hardware report and a lock reviewed for hardware."""
        report = self.report or {}
        lock = self.lock or {}
        reviewed = lock.get("reviewed_by") if isinstance(lock, dict) else None
        return (self.passed() and isinstance(report, dict) and report.get("backend") == "hardware"
                and report.get("passed") is True and report.get("evidence_state") == "hardware_checked"
                and isinstance(reviewed, dict) and reviewed.get("scope") == "hardware"
                and report.get("report_digest") == ((self.result or {}).get("gate") or {}).get("digest"))

    def committed_files(self) -> list[str]:
        """The files of the package a record names: a generated gate report only as hardware evidence."""
        keep = self.hardware_checked()
        return sorted(name for name in self.docs if name not in GENERATED or keep)

    def evidence_state(self) -> str | None:
        if self.hardware_checked():
            return "hardware_checked"
        if self.passed():
            return "contract_checked"
        return None

    def adapter_state(self) -> str | None:
        if self.passed():
            return "runnable"
        if self.lock is not None:
            return "packaged"
        return None

    def package_status(self) -> str:
        """``pass`` (a passing RESULT.json with a gate digest), ``blocked``, ``skip-proposed``, or
        ``in_progress`` (no RESULT.json yet, or one that does not record a valid outcome)."""
        if self.passed():
            return "pass"
        if self.status in ("blocked", "skip-proposed"):
            return str(self.status)
        return "in_progress"

    def blocked_on(self) -> list[str]:
        if self.status in ("blocked", "skip-proposed"):
            codes = (self.result or {}).get("blocked_on") or []
            return sorted({str(c) for c in codes if isinstance(c, str)})
        return []

    def to_vendor(self) -> dict[str, Any]:
        """The overlay summary recorded in the registry record's ``x-vendor``."""
        out: dict[str, Any] = {"driver_dir": self.path, "files": self.committed_files()}
        if self.status:
            out["status"] = self.status
        state = self.evidence_state()
        if state:
            out["evidence_state"] = state
        lock = self.lock or {}
        if isinstance(lock, dict):
            commit = (lock.get("upstream") or {}).get("commit") if isinstance(lock.get("upstream"), dict) else None
            if commit:
                out["commit"] = commit
            author = lock.get("authored_by")
            if isinstance(author, dict) and author.get("kind"):
                out["authored_by"] = author.get("kind")
            out["reviewed"] = bool(lock.get("reviewed_by"))
        gate = (self.result or {}).get("gate") if isinstance(self.result, dict) else None
        if isinstance(gate, dict) and gate.get("digest"):
            out["gate_digest"] = gate["digest"]
        if self.blocked_on():
            out["blocked_on"] = self.blocked_on()
        if self.errors:
            out["errors"] = list(self.errors)
        return out


def load(drivers_dir: str = DRIVERS_DIR) -> dict[str, Overlay]:
    """``{"<track>/<owner>__<repo>": Overlay}`` for every driver directory (read-only)."""
    out: dict[str, Overlay] = {}
    for track in TRACKS:
        base = os.path.join(drivers_dir, track)
        if not os.path.isdir(base):
            continue
        for name in sorted(os.listdir(base)):
            path = os.path.join(base, name)
            if not os.path.isdir(path) or not _DIR_NAME.match(name):
                continue
            overlay = Overlay(key=f"{track}/{name}", path=os.path.relpath(path, WORKSPACE).replace(os.sep, "/"))
            for file in FILES:
                full = os.path.join(path, file)
                if not os.path.isfile(full):
                    continue
                try:
                    with open(full, encoding="utf-8") as fh:
                        overlay.docs[file] = json.load(fh)
                except (OSError, ValueError) as exc:
                    overlay.errors.append(f"{file}: unreadable ({type(exc).__name__})")
            out[overlay.key] = overlay
    return out


def key_for(local_path: str) -> str:
    """Overlay key of a registry record's ``local_path`` (``labs/<owner>/<repo>``)."""
    track, owner, repo = str(local_path).split("/")[:3]
    return f"{track}/{owner}__{repo}"


def tree_digests(*roots: str) -> dict[str, str]:
    """sha256 of every file below the given directories (relative path -> digest), for no-write checks."""
    out: dict[str, str] = {}
    for root in roots:
        if not os.path.isdir(root):
            continue
        for path in sorted(glob.glob(os.path.join(root, "**", "*"), recursive=True)):
            if os.path.isfile(path):
                with open(path, "rb") as fh:
                    out[os.path.relpath(path, WORKSPACE).replace(os.sep, "/")] = hashlib.sha256(fh.read()).hexdigest()
    return out
